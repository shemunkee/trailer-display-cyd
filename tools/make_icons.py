"""Draws the bottom-nav icons from the mockup (24x24 line icons, stroke 2,
round caps) into 20x20 8-bit alpha bitmaps for LVGL (A8, recolored at runtime).

Usage: python tools/make_icons.py > include/nav_icons.h
Pure Python, no imaging libraries. Shapes are the mockup's SVG paths turned
into polylines; the stroke is the distance to those segments, supersampled.
"""
import math

SIZE = 20
SCALE = SIZE / 24.0
HALF_W = 1.0  # stroke width 2 in 24-unit space
SS = 4  # supersampling per axis


def arc(cx, cy, r, a0, a1, n=24):
    # angles in degrees, SVG coordinates (y down), from a0 to a1
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def cubic(p0, p1, p2, p3, n=16):
    out = []
    for i in range(n + 1):
        t = i / n
        mt = 1 - t
        out.append((mt**3 * p0[0] + 3 * mt * mt * t * p1[0] + 3 * mt * t * t * p2[0] + t**3 * p3[0],
                    mt**3 * p0[1] + 3 * mt * mt * t * p1[1] + 3 * mt * t * t * p2[1] + t**3 * p3[1]))
    return out


def rrect(x, y, w, h, r):
    pts = []
    pts += arc(x + w - r, y + r, r, -90, 0, 6)
    pts += arc(x + w - r, y + h - r, r, 0, 90, 6)
    pts += arc(x + r, y + h - r, r, 90, 180, 6)
    pts += arc(x + r, y + r, r, 180, 270, 6)
    return pts + [pts[0]]


def line(x0, y0, x1, y1):
    return [(x0, y0), (x1, y1)]


