print(f"#define NAV_ICON_SIZE {SIZE}\n")
for name, polys in ICONS.items():
    px = render(polys)
    print(f"static const uint8_t nav_icon_{name}[{SIZE * SIZE}] = {{")
    for r in range(SIZE):
        print("  " + ",".join(f"{v:3d}" for v in px[r * SIZE:(r + 1) * SIZE]) + ",")
    print("};\n")

