"""Make include/ota_ca.h: the root certificates the display trusts for update
downloads from GitHub (SPEC.md 5.7). Run from the project folder:
    python tools/make_ota_ca.py [path to a CA bundle]

The default bundle is the one that comes with Git for Windows. To see which
roots GitHub uses now:
    openssl s_client -connect github.com:443 -showcerts
    openssl s_client -connect release-assets.githubusercontent.com:443 -showcerts
"""

import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "include" / "ota_ca.h"
DEFAULT_BUNDLE = r"C:\Program Files\Git\usr\ssl\certs\ca-bundle.crt"
NAMES = [
    "USERTrust ECC Certification Authority",          # github.com today
    "Sectigo Public Server Authentication Root E46",  # github.com today (cross-signed by the one above)
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root R46",
    "ISRG Root X1",  # release file downloads today (Let's Encrypt)
    "ISRG Root X2",
    "DigiCert Global Root G2",  # used by GitHub before
]


def main():
    bundle = Path(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_BUNDLE).read_text()
    ssl = shutil.which("openssl") or r"C:\Program Files\Git\usr\bin\openssl.exe"
    lines = [
        "// Root certificates for update downloads from GitHub (SPEC.md 5.7), checked on",
        "// every HTTPS connection. github.com chains to USERTrust ECC / Sectigo E46; the",
        "// release file downloads (release-assets / objects.githubusercontent.com) chain to",
        "// ISRG Root X1 (Let's Encrypt). The others are their sibling roots and a former",
        "// GitHub root, so a routine certificate change at GitHub doesn't break updates.",
        "// Generated by tools/make_ota_ca.py; chains last checked 2026-11-22.",
        "#pragma once",
        "",
        "static const char OTA_CA[] =",
    ]
    for name in NAMES:
        m = re.search(r"^# " + re.escape(name) + r"\n(-----BEGIN CERTIFICATE-----\n.*?-----END CERTIFICATE-----)", bundle, re.S | re.M)
        if not m:
            sys.exit(f"{name} not found in the bundle")
        pem = m.group(1)
        end = subprocess.run([ssl, "x509", "-noout", "-enddate"], input=pem, capture_output=True, text=True, check=True)
        lines.append(f"    // {name} (valid to {end.stdout.strip().split('=', 1)[1]})")
        lines += [f'    "{line}\\n"' for line in pem.splitlines()]
    lines[-1] += ";"
    OUT.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)} with {len(NAMES)} roots")


if __name__ == "__main__":
    main()
