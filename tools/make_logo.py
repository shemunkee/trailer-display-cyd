"""Make include/logo_rgb565.h, the snooze logo (SPEC.md 6.10), from the original artwork.

The original is a 320x240 RGB565 picture on black (tools/logo_source_rgb565.h).
Only the part with the logo is kept, in its original colors: the black around it
is cropped off and the firmware draws the crop on a black screen at the same
spot. About 69 KB of flash instead of 150 KB, which leaves room for two
firmware slots (OTA).

Pure Python, no extra packages. Run from the project folder:
    python tools/make_logo.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "logo_source_rgb565.h"
OUT = ROOT / "include" / "logo_rgb565.h"
W, H = 320, 240


def main():
    text = SRC.read_text()
    body = text[text.index("{"):]
    px = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{4})", body)][: W * H]
    assert len(px) == W * H, f"expected {W * H} pixels, found {len(px)}"

    # Crop to every pixel that isn't pure black, so no faint edge is lost
    xs = [i % W for i, v in enumerate(px) if v]
    ys = [i // W for i, v in enumerate(px) if v]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    cw, ch = x1 - x0 + 1, y1 - y0 + 1
    crop = [px[y * W + x] for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)]

    lines = [
        "// Snooze logo (SPEC.md 6.10): the original artwork in RGB565, cropped to the logo;",
        "// drawn on black at LOGO_X, LOGO_Y. Generated by tools/make_logo.py from",
        "// tools/logo_source_rgb565.h; don't edit by hand.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define LOGO_W {cw}",
        f"#define LOGO_H {ch}",
        "// Where the crop sat in the 320x240 original, so it shows in the same place",
        f"#define LOGO_X {x0}",
        f"#define LOGO_Y {y0}",
        "",
        "// Same 16-bit layout LVGL renders in (RGB565, native byte order)",
        "static const uint16_t logo_rgb565[LOGO_W * LOGO_H] = {",
    ]
    for i in range(0, len(crop), 16):
        lines.append("  " + ", ".join(f"0x{v:04X}" for v in crop[i : i + 16]) + ",")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {cw}x{ch} at ({x0},{y0}), {len(crop) * 2} bytes")


if __name__ == "__main__":
    main()
