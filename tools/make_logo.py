"""Make include/logo_a8.h, the snooze logo (SPEC.md 6.10), from the original artwork.

The original is a 320x240 RGB565 picture on black (tools/logo_source_rgb565.h).
The display shows it as one color (the solar pink) on black, so only the shape
is kept: an 8-bit alpha mask cropped to the logo, which the firmware tints.
That is about 34 KB of flash instead of 150 KB, which leaves room for two
firmware slots (OTA).

Pure Python, no extra packages. Run from the project folder:
    python tools/make_logo.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "logo_source_rgb565.h"
OUT = ROOT / "include" / "logo_a8.h"
W, H = 320, 240
# Brightness at and above which a pixel counts as fully logo; below it fades out
# so the edges stay smooth. The darkest blue stripes inside the logo are well above it.
SOLID = 40


def main():
    text = SRC.read_text()
    body = text[text.index("{"):]
    px = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{4})", body)][: W * H]
    assert len(px) == W * H, f"expected {W * H} pixels, found {len(px)}"

    def lum(v):
        r = ((v >> 11) & 31) * 255 // 31
        g = ((v >> 5) & 63) * 255 // 63
        b = (v & 31) * 255 // 31
        return (r * 299 + g * 587 + b * 114) // 1000

    alpha = [min(255, lum(v) * 255 // SOLID) for v in px]
    xs = [i % W for i, a in enumerate(alpha) if a]
    ys = [i // W for i, a in enumerate(alpha) if a]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    cw, ch = x1 - x0 + 1, y1 - y0 + 1
    crop = [alpha[y * W + x] for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)]

    lines = [
        "// Snooze logo (SPEC.md 6.10): 8-bit alpha mask, tinted solar pink on black by the firmware.",
        "// Generated by tools/make_logo.py from tools/logo_source_rgb565.h; don't edit by hand.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define LOGO_W {cw}",
        f"#define LOGO_H {ch}",
        f"// Where the crop sat in the 320x240 original, so it shows in the same place",
        f"#define LOGO_X {x0}",
        f"#define LOGO_Y {y0}",
        "",
        "static const uint8_t logo_a8[LOGO_W * LOGO_H] = {",
    ]
    for i in range(0, len(crop), 24):
        lines.append("  " + ", ".join(f"0x{a:02x}" for a in crop[i : i + 24]) + ",")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {cw}x{ch} at ({x0},{y0}), {len(crop)} bytes")


if __name__ == "__main__":
    main()
