"""Make the OTA signing key pair (SPEC.md 5.7). Run once, from the project folder:
    python tools/ota_keygen.py

- Private key: %USERPROFILE%\\.victron_cyd\\ota_signing_key.pem. It never goes in
  the project or git. Back it up somewhere safe (a password manager or a USB
  stick): without it no new update can be signed, and every display would need
  a USB flash with a new key.
- Public key: include/ota_pubkey.h, built into the firmware. Not secret.

Refuses to overwrite an existing private key. Needs openssl (comes with Git for Windows).
"""

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KEY_DIR = Path.home() / ".victron_cyd"
KEY = KEY_DIR / "ota_signing_key.pem"
PUB_H = ROOT / "include" / "ota_pubkey.h"


def openssl():
    found = shutil.which("openssl")
    if found:
        return found
    for p in (r"C:\Program Files\Git\usr\bin\openssl.exe", r"C:\Program Files\Git\mingw64\bin\openssl.exe"):
        if Path(p).exists():
            return p
    sys.exit("openssl not found. Install Git for Windows, or put openssl on the PATH.")


def main():
    ssl = openssl()
    if KEY.exists():
        print(f"Private key already exists at {KEY}; leaving it alone.")
    else:
        KEY_DIR.mkdir(exist_ok=True)
        subprocess.run([ssl, "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", str(KEY)], check=True)
        print(f"Made the private key: {KEY}")
        print("Back it up somewhere safe. Never put it in the project folder or git.")

    pub = subprocess.run([ssl, "ec", "-in", str(KEY), "-pubout"], check=True, capture_output=True, text=True).stdout
    lines = [
        "// Public half of the OTA signing key (SPEC.md 5.7). The firmware only installs",
        "// an update whose manifest is signed with the matching private key, which lives",
        "// on Sabrina's laptop only. Not secret. Generated by tools/ota_keygen.py.",
        "#pragma once",
        "",
        "static const char OTA_PUBKEY[] =",
    ]
    lines += [f'    "{line}\\n"' for line in pub.strip().splitlines()]
    lines[-1] += ";"
    PUB_H.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"Wrote {PUB_H.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
